function results = runChecks()
%RUNCHECKS Run all owned analytical and independent-study regression tests in MATLAB.
% From MATLAB_Code: addpath('tests'); results = runChecks();
folder = fileparts(mfilename('fullpath'));
results = runtests({fullfile(folder,'testOpticalModels.m'), ...
    fullfile(folder,'testCoverageModel.m'), ...
    fullfile(folder,'testAnalysisHandoff.m'), ...
    fullfile(folder,'testStudyWorkflow.m'), ...
    fullfile(folder,'testRemainingModels.m'), ...
    fullfile(folder,'testIndependentStudies.m'), ...
    fullfile(folder,'testMissionIntegration.m')});
assertSuccess(results);
end
