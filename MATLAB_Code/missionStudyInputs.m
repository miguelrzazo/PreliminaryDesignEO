function studies = missionStudyInputs(design,outputDirectory)
%MISSIONSTUDYINPUTS Share the selected design across the independent studies.
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2, outputDirectory = fullfile(root,'Compiled data','Mission'); end
if nargin < 1
    design = table2struct(readtable(fullfile(outputDirectory,'selected_design.csv')));
end
mu = 3.986004418e14; radius_m = 6378.137e3;
J2 = 1.082629989052e-3; J3 = -2.5327e-6;
sunRate = 2*pi/(365.2421897*86400);
a = radius_m+design.Altura_km*1000;
inclination_deg = acosd(-2*a^(7/2)*sunRate/(3*J2*radius_m^2*sqrt(mu)));
eccentricity = -J3/(2*J2)*(radius_m/a)*sind(inclination_deg);
studies.frozen = struct('earthGravitationalParameter_m3_s2',mu,'earthRadius_m',radius_m, ...
    'earthJ2',J2,'earthJ3',J3,'sunNodalRate_rad_s',sunRate, ...
    'selectedAltitude_km',design.Altura_km,'latitudeBounds_deg',[25 49], ...
    'missionDuration_days',8*365.25,'outputDirectory',fullfile(outputDirectory,'Frozen'), ...
    'writeOutputs',true);
studies.contact = struct('startTime',datetime('28-Apr-2024 00:00:00','TimeZone','UTC'), ...
    'duration_days',7,'sampleTime_s',10,'groundStationName','Fairbanks (referencia geográfica)', ...
    'groundStationLatitude_deg',64.84,'groundStationLongitude_deg',-147.712, ...
    'minimumElevation_deg',10,'satelliteCount',design.Num_Satelites, ...
    'telescopesPerSatellite',design.Num_Telescopios,'altitude_km',design.Altura_km, ...
    'earthRadius_km',radius_m/1000,'eccentricity',eccentricity, ...
    'inclination_deg',inclination_deg,'argumentOfPerigee_deg',90,'propagator','sgp4', ...
    'earthGravitationalParameter_m3_s2',mu,'localTimeAscendingNode_h',6, ...
    'groundSampleDistance_m',design.GSD,'nominalSwath_km',design.Swath_Adquirido_km, ...
    'bandCount',3,'bitsPerBand',12,'memoryCapacity_GB',2, ...
    'regionBounds',struct('latMin',25,'latMax',49,'lonMin',-125,'lonMax',-66), ...
    'referenceRate_Mbps',10,'outputDirectory',fullfile(outputDirectory,'Contacts'), ...
    'writeOutputs',true);
studies.deorbit = struct('nominalAltitude_km',design.Altura_km, ...
    'missionDuration_years',8,'maintenanceDrop_percent',2,'reentryAltitude_km',100, ...
    'deorbitRequirement_days',365,'dryMass_kg',design.Masa_Seca_Satelite_kg, ...
    'dragArea_m2',design.Area_Satelite_m2,'maintenanceFuel_kg',design.Masa_Combustible_kg, ...
    'satelliteCount',design.Num_Satelites,'dragCoefficient',2.5,'specificImpulse_s',220, ...
    'outputDirectory',fullfile(outputDirectory,'EndOfLife'),'writeOutputs',true);
studies.rgt = struct('earthGravitationalParameter_m3_s2',mu,'earthRadius_m',radius_m, ...
    'earthJ2',J2,'earthJ3',J3,'earthRotation_rad_s',7.292115373194e-5, ...
    'sunNodalRate_rad_s',sunRate,'altitudes_km',200:2:1000, ...
    'rootBounds_m',[200e3 1000e3],'referenceAltitude_km',design.Altura_km, ...
    'maxRepeatDays',30,'rootTolerance',1e-10,'maxIterations',100, ...
    'outputDirectory',fullfile(outputDirectory,'RGT'),'writeOutputs',true);
end
