function snrGrid = SNRfunction(wavelength_m, pixelSize_m, quantumEfficiency, ...
    transmittance, groundSampleDistance_m, obstructionRatio, ...
    altitudes_km, pupilDiameters_mm, outputPrefix, ...
    telescopeName, detectorIndex, snrRequirement, writeOutputs)
%SNRFUNCTION Preserve positional calls and output filenames used by master.m.
% Set writeOutputs=false to obtain the numerical grid without exports.
if nargin < 13, writeOutputs = true; end
[snrGrid, model] = computeSnrGrid(wavelength_m, pixelSize_m, quantumEfficiency, ...
    transmittance, groundSampleDistance_m, obstructionRatio, ...
    altitudes_km, pupilDiameters_mm, snrRequirement);
if writeOutputs
    writeSnrResult(snrGrid, wavelength_m, pixelSize_m, quantumEfficiency, ...
        transmittance, groundSampleDistance_m, obstructionRatio, ...
        altitudes_km, pupilDiameters_mm, outputPrefix, ...
        telescopeName, detectorIndex, snrRequirement, model);
end
end
