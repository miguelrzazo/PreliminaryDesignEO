function [coverageGrid_days, diagnostics] = CoverageRevisitCalc( ...
    groundSampleDistance_m, altitudes_km, swaths_km, ...
    revisitRequirement_days, detectorPixelCount, telescopeFov_deg, ...
    satelliteCount, telescopeCount, detectorIndex, telescopeName, ...
    overlapFraction, cloudFraction, maxDetectorCount, writeOutputs)
%COVERAGEREVISITCALC Preserve positional calls and filenames used by master.m.
% Set writeOutputs=false to obtain numerical results without creating files.
% Solver failures are returned in diagnostics and reported without muting warnings.
if nargin < 14, writeOutputs = true; end
[coverageGrid_days, diagnostics] = computeCoverageGrid( ...
    groundSampleDistance_m, altitudes_km, swaths_km, ...
    revisitRequirement_days, detectorPixelCount, telescopeFov_deg, ...
    satelliteCount, telescopeCount, overlapFraction, cloudFraction, maxDetectorCount);
solverErrorCount = nnz(~cellfun(@isempty, diagnostics.solverErrors));
if solverErrorCount > 0
    warning('eo:CoverageSolverFailure', ...
        '%d coverage cells failed. Inspect diagnostics.solverErrors for details.', solverErrorCount);
end
if writeOutputs
    configurationName = sprintf('%d Satelite(s); %d Telescopio(s): %s; Detector %d', ...
        satelliteCount, telescopeCount, strrep(telescopeName, ' ', ''), detectorIndex);
    writeCoverageResult(coverageGrid_days, altitudes_km, swaths_km, ...
        revisitRequirement_days, diagnostics, configurationName);
end
end
