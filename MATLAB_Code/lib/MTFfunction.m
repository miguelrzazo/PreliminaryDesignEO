function mtfGrid = MTFfunction(wavelength_m, pixelSize_m, detectorMtf, ...
    alignmentMtf, groundSampleDistance_m, obstructionRatio, ...
    altitudes_km, pupilDiameters_mm, outputPrefix, ...
    telescopeName, detectorIndex, mtfRequirement, writeOutputs)
%MTFFUNCTION Preserve positional calls and output filenames used by master.m.
% Set writeOutputs=false to obtain the numerical grid without exports.
if nargin < 13, writeOutputs = true; end
mtfGrid = computeMtfGrid(wavelength_m, pixelSize_m, detectorMtf, ...
    alignmentMtf, groundSampleDistance_m, obstructionRatio, ...
    altitudes_km, pupilDiameters_mm, mtfRequirement);
if writeOutputs
    writeMtfResult(mtfGrid, wavelength_m, pixelSize_m, detectorMtf, ...
        alignmentMtf, groundSampleDistance_m, obstructionRatio, ...
        altitudes_km, pupilDiameters_mm, outputPrefix, ...
        telescopeName, detectorIndex, mtfRequirement);
end
end
